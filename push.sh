#!/bin/bash

# Joker Store Auto-Push Script 🃏

echo "---------------------------------------"
echo "🚀 جاري بدء عملية الرفع إلى GitHub..."
echo "---------------------------------------"

# 0. تشغيل اختبارات فحص الكود
echo "🔍 جاري فحص الكود قبل الرفع..."
# سنفترض وجود سكريبت test في package.json، إذا لم يوجد يمكنك استخدام node --check server.js كفحص سريع للسنتاكس
if npm test; then
    echo "✅ نجحت جميع الفحوصات والاختبارات."
else
    echo "❌ فشل فحص الكود! يرجى إصلاح الأخطاء قبل الرفع."
    echo "---------------------------------------"
    exit 1
fi

# 1. تحقق مما إذا كان هناك تغييرات فعلاً
if [ -z "$(git status --porcelain)" ]; then
    echo "✨ لا توجد تغييرات جديدة للرفع. المستودع نظيف!"
    echo "---------------------------------------"
    exit 0
fi

# 1.5. سحب أحدث التغييرات لتجنب التعارضات
echo "🔄 جاري سحب أحدث التغييرات من المستودع..."
if git pull --rebase origin main; then
    echo "✅ تم تحديث المستودع المحلي بنجاح."
else
    echo "❌ فشل سحب التغييرات! يرجى حل التعارضات يدوياً قبل الرفع."
    echo "---------------------------------------"
    exit 1
fi

# 2. إضافة كل التغييرات
git add .
echo "✅ تمت إضافة الملفات إلى منطقة التجهيز."

# 3. طلب رسالة الـ Commit
read -p "📝 أدخل رسالة التحديث (أو اضغط Enter لاستخدام تاريخ اليوم): " commit_msg
if [ -z "$commit_msg" ]; then
  commit_msg="تحديث تلقائي بتاريخ: $(date '+%Y-%m-%d %H:%M:%S')"
fi

git commit -m "$commit_msg"

# 3. الرفع إلى الفرع الرئيسي
echo "📡 جاري الرفع إلى GitHub (Main branch)..."
if git push origin main; then
    echo "---------------------------------------"
    echo "🎉 تم الرفع بنجاح! ريندر (Render) سيبدأ النشر الآن."
    echo "---------------------------------------"
else
    echo "❌ فشل الرفع إلى GitHub. تأكد من إعدادات المستودع أو اتصال الإنترنت."
    exit 1
fi