// يبني نسخاً مصغّرة (minified) من أكبر ملفات الواجهة.
// - الملفات الناتجة تُرفع مع المستودع ويخدمها الخادم في الإنتاج فقط (انظر app.js).
// - التطوير يبقى على الملفات الأصلية القابلة للقراءة.
// - التشغيل: npm run build:assets

const fs = require('fs');
const path = require('path');
const CleanCSS = require('clean-css');
const { minify } = require('terser');

const PUBLIC_DIR = path.join(__dirname, '..', 'public');
const BANNER = '/*! Joker Store — auto-generated by scripts/build-assets.js. Do not edit directly. */\n';

/**
 * تنسيق الحجم للطباعة.
 * @param {number} bytes - الحجم بالبايت.
 * @returns {string}
 */
function kb(bytes) {
    return `${(bytes / 1024).toFixed(1)} KB`;
}

/**
 * بناء style.min.css.
 * @returns {{file: string, before: number, after: number, ratio: number}}
 */
function buildCss() {
    const source = path.join(PUBLIC_DIR, 'style.css');
    const target = path.join(PUBLIC_DIR, 'style.min.css');
    const css = fs.readFileSync(source, 'utf8');
    const result = new CleanCSS({
        level: 2,
        // لا نحذف تعليقات الترخيص المهمة
        format: false
    }).minify(css);

    if (result.errors && result.errors.length) {
        throw new Error(`clean-css: ${result.errors.join('; ')}`);
    }

    fs.writeFileSync(target, BANNER + result.styles, 'utf8');
    return {
        file: 'style.min.css',
        before: Buffer.byteLength(css),
        after: Buffer.byteLength(result.styles),
        ratio: result.styles.length / css.length
    };
}

/**
 * بناء ملفات JS المصغّرة (ES Modules).
 * @returns {Promise<Array<{file: string, before: number, after: number, ratio: number}>>}
 */
async function buildJs() {
    const files = ['script.js', 'ui.js'];
    const results = [];
    for (const name of files) {
        const source = path.join(PUBLIC_DIR, name);
        const target = path.join(PUBLIC_DIR, name.replace(/\.js$/, '.min.js'));
        const code = fs.readFileSync(source, 'utf8');
        const output = await minify(code, {
            module: true,
            compress: { passes: 2, drop_debugger: true },
            mangle: true,
            format: { comments: false }
        });
        if (!output.code) throw new Error(`terser: no output for ${name}`);
        fs.writeFileSync(target, BANNER + output.code, 'utf8');
        results.push({
            file: path.basename(target),
            before: Buffer.byteLength(code),
            after: Buffer.byteLength(output.code),
            ratio: output.code.length / code.length
        });
    }
    return results;
}

async function main() {
    const started = Date.now();
    const results = [buildCss(), ...(await buildJs())];
    for (const row of results) {
        console.log(
            `${row.file.padEnd(18)} ${kb(row.before).padStart(10)} → ${kb(row.after).padStart(10)}  (-${Math.round((1 - row.ratio) * 100)}%)`
        );
    }
    console.log(`done in ${Date.now() - started}ms`);
}

main().catch((error) => {
    console.error('❌ build:assets failed:', error.message);
    process.exit(1);
});
